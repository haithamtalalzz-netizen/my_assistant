// بيانات «القصص والسيرة» — كلها إشارات لمصادر متحقّقة مدمجة فى التطبيق:
//   • نص الآيات: assets/quran/quran.json  (مصدر Tanzil — مصحف المدينة)
//   • التفسير: assets/quran/tafsir_muyassar.json (التفسير الميسّر — مجمع الملك فهد)
// مافيش أى سرد مؤلَّف هنا: كل قصة = نطاقات آيات (سورة + من–إلى) تُعرض بنصّها،
// والمقدّمة سطر تعريفى محايد (اسم + أين وردت). الأربعون النووية نصّها من ملف
// أصول موثوق منفصل (assets/hadith/arbain_nawawi.json).

/// مقطع قصة = نطاق آيات متّصل داخل سورة واحدة.
class StoryPassage {
  final int surah;
  final int from;
  final int to;
  final String label; // وصف مختصر للمقطع (اختيارى)
  const StoryPassage(this.surah, this.from, this.to, [this.label = '']);
}

/// قصة (نبى أو قصة قرآنية).
class QuranStory {
  final String name;
  final String emoji;

  /// سطر تعريفى محايد (مش سرد) — اسم + إشارة لموضعها.
  final String intro;
  final List<StoryPassage> passages;
  const QuranStory({
    required this.name,
    required this.emoji,
    required this.intro,
    required this.passages,
  });
}

